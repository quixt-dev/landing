/**
 * Builds a 2°×2° land/ocean bitmask from Natural Earth (world-atlas, 110m) for the
 * revolving dot globes. Output: src/lib/graphics/landmask.ts (base64, ~2 KB).
 * Usage: node scripts/generate-landmask.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { feature } from 'topojson-client';
import { geoContains } from 'd3-geo';

const root = resolve(import.meta.dirname, '..');
const topo = JSON.parse(readFileSync(resolve(root, 'node_modules/world-atlas/land-110m.json'), 'utf8'));
const land = feature(topo, topo.objects.land);
const ROWS = 90, COLS = 180; // row 0 = lat -89 … row 89 = lat 89; col 0 = lon -179 … col 179 = lon 179
const bytes = new Uint8Array(Math.ceil((ROWS * COLS) / 8));
let count = 0;
for (let r = 0; r < ROWS; r++) for (let c = 0; c < COLS; c++) {
  const lat = -89 + r * 2, lon = -179 + c * 2;
  if (geoContains(land, [lon, lat])) { const i = r * COLS + c; bytes[i >> 3] |= 1 << (i & 7); count++; }
}
const b64 = Buffer.from(bytes).toString('base64');
writeFileSync(resolve(root, 'src/lib/graphics/landmask.ts'), `/* Generated by scripts/generate-landmask.mjs from Natural Earth 110m land (public domain). Do not edit. */
const B64 = '${b64}';
const ROWS = ${ROWS}, COLS = ${COLS};
let bits: Uint8Array | null = null;
const decode = () => {
  if (bits) return bits;
  const bin = typeof atob === 'function' ? atob(B64) : Buffer.from(B64, 'base64').toString('binary');
  bits = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bits[i] = bin.charCodeAt(i);
  return bits;
};
/** True when the given latitude/longitude (degrees) falls on land (2° resolution). */
export function isLand(lat: number, lon: number) {
  const b = decode();
  const r = Math.min(ROWS - 1, Math.max(0, Math.round((lat + 89) / 2)));
  const c = (((Math.round((lon + 179) / 2)) % COLS) + COLS) % COLS;
  const i = r * COLS + c;
  return (b[i >> 3] >> (i & 7)) & 1;
}
`);
console.log(`land cells: ${count}/${ROWS * COLS} (${((100 * count) / (ROWS * COLS)).toFixed(1)}%), ${b64.length} b64 chars`);
